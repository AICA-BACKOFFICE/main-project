-- 2026-10-20 미디어 관리(사용자 요청): 관리자 · 서포터즈가 올린 사진 · 동영상을 모두 함께 쓰는 목록(표 7개 → 8개).
-- 파일 자체는 저장소(지금은 서버의 업로드 폴더, 나중에 클라우드 저장소)에 두고, 이 표에는 이름 · 종류 · 저장소 안 위치 · 크기 · 올린 사람만 적는다.
-- 주소는 설정(backoffice.media-base-url, 기본 /uploads/) + storage_key 로 만든다 — 저장소를 옮겨도 이 표는 그대로.
-- 이름(name)은 바꿀 수 있고, 바꿔도 파일 · 주소는 그대로라 그 미디어를 쓰는 게시글은 영향이 없다.
-- 휴지통 칸은 다른 게시글 표와 같다(삭제하면 DELETED · 지운 시각, 휴지통에서 복원 · 완전 삭제 — 완전 삭제하면 파일도 지운다).
CREATE TABLE media (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_type          VARCHAR(10)  NOT NULL,                    -- IMAGE 이미지 · VIDEO 동영상
    name                VARCHAR(200) NOT NULL,                    -- 미디어 이름(목록 · 검색, 바꿀 수 있음)
    original_name       VARCHAR(255) NOT NULL,                    -- 처음 올릴 때 파일 이름(참고용)
    storage_key         VARCHAR(300) NOT NULL,                    -- 저장소 안 위치(2026/10/a1b2.webp)
    content_type        VARCHAR(100) NOT NULL,                    -- image/webp · video/mp4 …
    file_size           BIGINT       NOT NULL,                    -- 바이트
    uploaded_by         BIGINT,                                   -- 올린 관리자(admin_users)
    status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE 사용 중 · DELETED 삭제됨(휴지통)
    status_before_trash VARCHAR(20),
    deleted_at          TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_media_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_media_type CHECK (media_type IN ('IMAGE', 'VIDEO')),
    CONSTRAINT ck_media_status CHECK (status IN ('ACTIVE', 'DELETED')),
    CONSTRAINT fk_media_uploader FOREIGN KEY (uploaded_by) REFERENCES admin_users (id) ON DELETE SET NULL
);
CREATE INDEX ix_media_list ON media (deleted_at, media_type, id DESC);

COMMENT ON TABLE media IS '미디어 관리: 함께 쓰는 사진 · 동영상. 파일은 저장소에, 이 표에는 정보만';
COMMENT ON COLUMN media.media_type IS '종류: IMAGE 이미지 · VIDEO 동영상';
COMMENT ON COLUMN media.name IS '미디어 이름(바꿀 수 있음. 바꿔도 파일 · 주소는 그대로)';
COMMENT ON COLUMN media.original_name IS '처음 올릴 때 파일 이름';
COMMENT ON COLUMN media.storage_key IS '저장소 안 위치. 주소 = backoffice.media-base-url + 이 값';
COMMENT ON COLUMN media.content_type IS '파일 형식';
COMMENT ON COLUMN media.file_size IS '크기(바이트)';
COMMENT ON COLUMN media.uploaded_by IS '올린 관리자(admin_users.id). 서포터즈는 자기가 올린 것만 이름 바꾸기 · 삭제';
COMMENT ON COLUMN media.status IS '상태: ACTIVE 사용 중 · DELETED 삭제됨(휴지통)';
COMMENT ON COLUMN media.status_before_trash IS '휴지통으로 옮기기 전 상태(복원하면 이 상태로)';
COMMENT ON COLUMN media.deleted_at IS '휴지통으로 옮긴 시각';
