-- 2026-10-20 카테고리 페이지 관리 버전 기록(사용자 요청): 백업 파일 폴더(data/pages/backups) 대신 DB 표에 남긴다(표 9개 → 10개).
-- 정식 배포 때 서버를 바꾸거나 여러 대가 되어도 DB 백업 하나로 함께 지켜지고, 누가 반영했는지도 남는다.
-- '사이트에 반영'(페이지 편집기 · 인사교 라이프 게시물 관리)을 할 때마다 반영된 페이지 HTML 전체를 한 줄로.
-- 반영 직전 사이트 파일이 마지막 기록과 다르면(처음 반영 · 다른 곳에서 바뀜) 그 모습도 먼저 한 줄로 남겨 되돌릴 수 있게 한다.
-- 예전 백업 파일은 처음 켤 때 한 번 이 표로 옮긴다(note '예전 백업 파일'). 페이지마다 최근 100개만 남긴다.
CREATE TABLE page_versions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id      VARCHAR(40)  NOT NULL,                      -- 페이지(about · stories · life · check …, backoffice.properties 의 페이지 번호)
    html         TEXT         NOT NULL,                      -- 그 버전의 페이지 HTML 전체
    content_hash VARCHAR(40)  NOT NULL,                      -- HTML 지문(SHA-1) — 같은 내용을 두 번 남기지 않게
    html_size    INT          NOT NULL,                      -- 크기(바이트, 목록 표시용)
    note         VARCHAR(100),                               -- 어디서: 사이트에 반영 · 인사교 라이프 게시물 관리 · 반영 전 사이트 상태 · 예전 백업 파일
    saved_by     BIGINT,                                     -- 반영한 관리자(admin_users)
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_page_versions_saved_by FOREIGN KEY (saved_by) REFERENCES admin_users (id) ON DELETE SET NULL
);
CREATE INDEX ix_page_versions_page ON page_versions (page_id, created_at DESC, id DESC);

COMMENT ON TABLE page_versions IS '카테고리 페이지 관리 버전 기록: 사이트에 반영할 때마다 페이지 HTML 전체를 한 줄로(페이지마다 최근 100개)';
COMMENT ON COLUMN page_versions.page_id IS '페이지 번호(about · stories · life · check …)';
COMMENT ON COLUMN page_versions.html IS '그 버전의 페이지 HTML 전체. 버전 기록에서 불러오면 편집 화면에 열림';
COMMENT ON COLUMN page_versions.content_hash IS 'HTML 지문(SHA-1). 바로 앞 기록과 같으면 다시 남기지 않음';
COMMENT ON COLUMN page_versions.html_size IS 'HTML 크기(바이트)';
COMMENT ON COLUMN page_versions.note IS '어디서 남긴 기록인지: 사이트에 반영 · 인사교 라이프 게시물 관리 · 반영 전 사이트 상태 · 예전 백업 파일';
COMMENT ON COLUMN page_versions.saved_by IS '반영한 관리자(admin_users.id). 계정을 지우면 비움';
COMMENT ON COLUMN page_versions.created_at IS '기록한 시각(반영한 시각)';
