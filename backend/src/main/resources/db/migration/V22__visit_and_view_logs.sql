-- 2026-10-20 방문 통계 표 두 개를 더한다(표 4개 → 6개). 사이트 페이지가 열릴 때 /api/public/track/visit,
-- 선배들의 이야기 글을 열 때 /api/public/track/posts/{종류}/{번호}/view 를 보내고, 관리자 홈 · 방문 통계 화면이 날짜별로 센다.
-- 방문자 번호(visitor_key)는 브라우저가 만든 임의 값이다. 이름 · IP 같은 개인정보는 저장하지 않는다.

-- 방문 기록: 사이트 페이지가 열릴 때마다 한 줄
CREATE TABLE visit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visited_on  DATE         NOT NULL,                       -- 방문 날짜(한국 시간). 날짜별로 센다
    visitor_key VARCHAR(64)  NOT NULL,                       -- 브라우저마다 만든 임의 번호. 같은 날 여러 번 와도 1명
    path        VARCHAR(300),                                -- 본 페이지(/stories/reviews.html)
    device      VARCHAR(10),                                 -- PC · MOBILE
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_visit_logs_day ON visit_logs (visited_on, visitor_key);

-- 게시물 조회 기록: 글을 열어 볼 때마다 한 줄. 글 번호는 표마다 1번부터라(V19) 종류 + 번호로 가리킨다
-- (세 표를 한 칸으로 참조할 수 없어 외래키 대신, 글을 완전히 지우거나 종류를 옮길 때 코드에서 함께 정리한다)
CREATE TABLE post_view_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_type   VARCHAR(20)  NOT NULL,                       -- review · interview · project
    post_id     BIGINT       NOT NULL,                       -- 그 표의 글 번호
    viewed_on   DATE         NOT NULL,                       -- 조회 날짜(한국 시간)
    visitor_key VARCHAR(64)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_post_view_logs_type CHECK (post_type IN ('review', 'interview', 'project'))
);
CREATE INDEX ix_post_view_logs_day ON post_view_logs (viewed_on, post_type, post_id);
CREATE INDEX ix_post_view_logs_post ON post_view_logs (post_type, post_id);
