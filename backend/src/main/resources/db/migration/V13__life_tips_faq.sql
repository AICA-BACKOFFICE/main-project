-- 인사교 라이프 › 생활 꿀팁 카드와 지원 전 체크 › 자주 묻는 질문을 DB에 둔다(전에는 사이트 페이지 HTML에 적혀 있었음).
-- 사이트는 공개 API(/api/public/life.js · /api/public/faq.js)로 이 내용을 받아 그리고, 백오피스가 꺼져 있을 때를 위해
-- 같은 내용을 사본(life/js/life-data.js · check/js/faq-data.js)으로도 쓴다. 처음 켤 때 사이트 페이지에 있던 카드 · 질문을 옮겨 온다.

-- 오늘 점심, 여기 어때요?: 식당 · 카페 카드. 사이트에는 식당 → 카페, 각각 sort_order 순으로
CREATE TABLE life_foods (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(10)  NOT NULL,                 -- food 식당 | cafe 카페
    party       VARCHAR(10)  NOT NULL,                 -- solo 혼밥(혼자) | group 여럿이
    walk_min    INT          NOT NULL,                 -- 걸어서 몇 분
    category    VARCHAR(20)  NOT NULL,                 -- 한식 등
    name        VARCHAR(60)  NOT NULL,
    menu        VARCHAR(120) NOT NULL,                 -- 메뉴 · 위치
    review      VARCHAR(300),                          -- 선배 후기(없어도 됨)
    example     BOOLEAN      NOT NULL DEFAULT FALSE,   -- '예시' 후기(관리자가 후기를 고치면 뗌)
    photo       VARCHAR(300),                          -- 사진(life/ 기준 주소). 없으면 '사진 준비 중'
    sort_order  INT          NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_life_foods_order ON life_foods (kind, sort_order);

-- 수업 끝나고, 바람 쐬러 가요: 묶음(walk 근처 산책길 · near 가까운 시설 · far 멀지만 가볼 만한 곳)마다 장소 카드
CREATE TABLE life_spots (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_key   VARCHAR(10)  NOT NULL,                 -- walk | near | far
    name        VARCHAR(60)  NOT NULL,
    distance    VARCHAR(60)  NOT NULL,                 -- 동쪽 · 약 1km
    fee         VARCHAR(40)  NOT NULL,                 -- 무료 등
    summary     VARCHAR(300) NOT NULL,
    photo_class VARCHAR(60),                           -- 사이트에 원래 있던 그림(life.css 의 im-이름)
    photo       VARCHAR(300),                          -- 올린 사진(life/ 기준 주소). photo_class 와 둘 중 하나
    sort_order  INT          NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_life_spots_order ON life_spots (group_key, sort_order);

-- 자주 묻는 질문. category 는 사이트 지원 전 체크 페이지의 분류 버튼(data-cat) 이름
CREATE TABLE faq_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category    VARCHAR(30)   NOT NULL,
    question    VARCHAR(400)  NOT NULL,
    answer      TEXT          NOT NULL,                -- 답(HTML: 링크 · 굵게 · 줄바꿈 · '확인 필요' 표시만)
    sort_order  INT           NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_faq_items_order ON faq_items (sort_order);
