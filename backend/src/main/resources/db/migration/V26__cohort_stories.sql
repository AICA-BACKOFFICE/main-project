-- 2026-10-20 기수별 이모저모(사용자 요청): 표만 먼저 만든다(표 8개 → 9개). 진짜 내용은 아직 안 받아서 데이터는 넣지 않는다.
-- 칸은 지금 사이트(stories/cohorts.html)의 더미 카드 기준: 대표 사진 · 제목 · 요약 · 기수 · 날짜 · 사진 여러 장 · 유튜브 영상(길이) · 본문 · 행사 태그.
-- 상태 · 휴지통 · 작성자 칸은 후기(reviews) · 인터뷰(interviews) · 프로젝트(projects) 표와 똑같다.
CREATE TABLE cohort_stories (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort              INT          NOT NULL,                     -- 기수(숫자, 카드에는 '7기')
    title               VARCHAR(200) NOT NULL,                     -- 제목
    summary             TEXT,                                      -- 카드에 보이는 짧은 글
    body                TEXT,                                      -- 글을 열면 보이는 본문(문단 사이는 빈 줄)
    event_date          DATE,                                      -- 있었던 날(카드에는 2026. 08. 20)
    tags                VARCHAR(200),                              -- 행사 태그(예: #입교식 #수료식). 여러 개
    photos              TEXT,                                      -- 사진(JSON: 대표 사진 · 사진 목록, 사진마다 설명)
    video_url           VARCHAR(300),                              -- 유튜브 주소(영상 글만)
    video_length        VARCHAR(8),                                -- 영상 길이(예: 5:40)
    status              VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    status_before_trash VARCHAR(20),
    author_id           BIGINT       NOT NULL,
    published_at        TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP,
    CONSTRAINT ck_cohort_stories_cohort CHECK (cohort BETWEEN 1 AND 99),
    CONSTRAINT ck_cohort_stories_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'HIDDEN', 'DELETED')),
    CONSTRAINT fk_cohort_stories_author FOREIGN KEY (author_id) REFERENCES admin_users (id)
);
CREATE INDEX ix_cohort_stories_cohort ON cohort_stories (cohort, event_date);
CREATE INDEX ix_cohort_stories_list ON cohort_stories (deleted_at, status, published_at);

COMMENT ON TABLE cohort_stories IS '기수별 이모저모 — 선배들의 이야기 › 기수별 이모저모. 기수마다 있었던 일(행사 사진 · 영상). 휴지통은 deleted_at';
COMMENT ON COLUMN cohort_stories.id IS '글 번호';
COMMENT ON COLUMN cohort_stories.cohort IS '기수(숫자)';
COMMENT ON COLUMN cohort_stories.title IS '제목';
COMMENT ON COLUMN cohort_stories.summary IS '카드에 보이는 짧은 글(요약)';
COMMENT ON COLUMN cohort_stories.body IS '본문(문단 사이는 빈 줄)';
COMMENT ON COLUMN cohort_stories.event_date IS '있었던 날(카드 날짜)';
COMMENT ON COLUMN cohort_stories.tags IS '행사 태그(예: #입교식 #중간발표회 #기업탐방 #취업박람회 #수료식). 여러 개';
COMMENT ON COLUMN cohort_stories.photos IS '사진(JSON: 대표 사진 · 사진 목록, 사진마다 설명(alt))';
COMMENT ON COLUMN cohort_stories.video_url IS '유튜브 영상 주소(영상 글만, 비우면 사진 글)';
COMMENT ON COLUMN cohort_stories.video_length IS '영상 길이(예: 5:40)';
COMMENT ON COLUMN cohort_stories.status IS '상태: DRAFT 임시저장 · PUBLISHED 게시 · HIDDEN 숨김 · DELETED 삭제됨(휴지통)';
COMMENT ON COLUMN cohort_stories.status_before_trash IS '휴지통으로 옮기기 전 상태(복원하면 이 상태로)';
COMMENT ON COLUMN cohort_stories.author_id IS '쓴 관리자(admin_users.id)';
COMMENT ON COLUMN cohort_stories.published_at IS '게시한 시각';
COMMENT ON COLUMN cohort_stories.created_at IS '처음 쓴 시각';
COMMENT ON COLUMN cohort_stories.updated_at IS '마지막으로 고친 시각';
COMMENT ON COLUMN cohort_stories.deleted_at IS '휴지통으로 옮긴 시각';
