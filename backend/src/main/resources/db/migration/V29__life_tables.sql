-- 2026-10-20 인사교 라이프 게시물 관리를 DB로(사용자 요청): 표 10개 → 14개. 표 이름은 aica-site 원래 DB(V15)와 같게.
-- DB가 원본이고, 카드(사진) 하나를 완료(게시) · 임시저장 · 삭제 · 복원 · 순서 바꾸기 할 때마다 백오피스가 '게시중'인 것만으로
-- 사이트 페이지(life/index.html)의 그 목록을 다시 쓴다(버전 기록 page_versions 에도 남음). 층 · 공간 이름 · 안내 글 같은 페이지 글은 카테고리 페이지 관리에서.
-- 상태 · 휴지통 칸은 게시글 · FAQ 와 같다: DRAFT 임시저장 · PUBLISHED 게시 · HIDDEN 미게시 · DELETED 삭제됨(휴지통), status_before_trash · deleted_at.
-- 임시저장은 빈칸이 있어도 되므로 이름 같은 칸은 비워 둘 수 있고, 게시할 때 서버가 빈칸을 확인한다.
-- 처음 켤 때 지금 페이지의 공간 · 사진 · 카드를 한 번 옮겨 담는다(LifeBoardService).

-- 1) 시설 공간: 사이트의 bx9s-층-번호 공간마다 한 줄(층 · 공간 이름은 페이지 글에서 읽어 맞춤)
CREATE TABLE life_facility_spaces (
    space_id    VARCHAR(20)  PRIMARY KEY,                  -- 공간(bx9s-1-0 등)
    floor_key   VARCHAR(10)  NOT NULL,                     -- 층 묶음(페이지의 data-g: 1 · 23 · 8 …)
    name        VARCHAR(40)  NOT NULL,                     -- 공간 이름(정문(입구) · AI 카페 …)
    badge       VARCHAR(10)  NOT NULL DEFAULT '',          -- 사진 넘김 왼쪽 위 표시: '' 없음 · ex 사진 예시 · tmp 임시 사진
    sort_order  INT          NOT NULL,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_life_facility_spaces_badge CHECK (badge IN ('', 'ex', 'tmp'))
);

-- 2) 시설 사진: 공간마다 넘겨 보는 사진
CREATE TABLE life_facility_photos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id            VARCHAR(20)  NOT NULL,
    photo_class         VARCHAR(60),                       -- 사이트에 원래 있던 그림(life.css 의 im-이름)
    photo               VARCHAR(300),                      -- 올린 사진(life/ 기준 주소 assets/uploads/…). photo_class 와 둘 중 하나
    zoom                VARCHAR(10),                       -- 확대(예: 230%, 비우면 꽉 차게)
    pos                 VARCHAR(30),                       -- 가운데에 보일 곳(예: 70% 40%)
    caption             VARCHAR(60),                       -- 사진 이름 · 설명(사진 아래 · 화면 낭독기)
    sort_order          INT          NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    status_before_trash VARCHAR(20),
    author_id           BIGINT,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP,
    CONSTRAINT ck_life_facility_photos_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'HIDDEN', 'DELETED')),
    CONSTRAINT fk_life_facility_photos_space FOREIGN KEY (space_id) REFERENCES life_facility_spaces (space_id),
    CONSTRAINT fk_life_facility_photos_author FOREIGN KEY (author_id) REFERENCES admin_users (id) ON DELETE SET NULL
);
CREATE INDEX ix_life_facility_photos_space ON life_facility_photos (space_id, deleted_at, sort_order);

-- 3) 오늘 점심, 여기 어때요?: 식당 · 카페 카드
CREATE TABLE life_foods (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                VARCHAR(10)  NOT NULL,                 -- food 식당 · cafe 카페
    party               VARCHAR(10)  NOT NULL DEFAULT 'solo',  -- solo 혼밥(혼자) · group 여럿이
    walk_min            INT,                                   -- 걸어서 몇 분(1~120)
    category            VARCHAR(20),                           -- 분류(한식 등)
    name                VARCHAR(60),                           -- 가게 이름
    menu                VARCHAR(120),                          -- 메뉴 · 위치
    review              VARCHAR(300),                          -- 선배 후기(없어도 됨)
    is_example          BOOLEAN      NOT NULL DEFAULT FALSE,   -- '예시' 후기(관리자가 후기를 고치면 뗌)
    photo               VARCHAR(300),                          -- 사진(life/ 기준 주소). 없으면 '사진 준비 중'
    sort_order          INT          NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    status_before_trash VARCHAR(20),
    author_id           BIGINT,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP,
    CONSTRAINT ck_life_foods_kind CHECK (kind IN ('food', 'cafe')),
    CONSTRAINT ck_life_foods_party CHECK (party IN ('solo', 'group')),
    CONSTRAINT ck_life_foods_walk CHECK (walk_min IS NULL OR walk_min BETWEEN 1 AND 120),
    CONSTRAINT ck_life_foods_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'HIDDEN', 'DELETED')),
    CONSTRAINT fk_life_foods_author FOREIGN KEY (author_id) REFERENCES admin_users (id) ON DELETE SET NULL
);
CREATE INDEX ix_life_foods_list ON life_foods (kind, deleted_at, sort_order);

-- 4) 수업 끝나고, 바람 쐬러 가요: 문화 · 여가 카드(걸어서 · 가까운 곳 · 먼 곳 묶음)
CREATE TABLE life_spots (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_key           VARCHAR(10)  NOT NULL,                 -- walk · near · far
    name                VARCHAR(60),                           -- 장소 이름
    distance            VARCHAR(60),                           -- 거리(동쪽 · 약 1km)
    fee                 VARCHAR(40),                           -- 요금(무료 등)
    summary             VARCHAR(300),                          -- 설명
    photo_class         VARCHAR(60),                           -- 사이트에 원래 있던 그림(life.css 의 im-이름)
    photo               VARCHAR(300),                          -- 올린 사진(life/ 기준 주소). photo_class 와 둘 중 하나
    sort_order          INT          NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    status_before_trash VARCHAR(20),
    author_id           BIGINT,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP,
    CONSTRAINT ck_life_spots_group CHECK (group_key IN ('walk', 'near', 'far')),
    CONSTRAINT ck_life_spots_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'HIDDEN', 'DELETED')),
    CONSTRAINT fk_life_spots_author FOREIGN KEY (author_id) REFERENCES admin_users (id) ON DELETE SET NULL
);
CREATE INDEX ix_life_spots_list ON life_spots (group_key, deleted_at, sort_order);

