-- 인사교 라이프 게시물 관리: 카드 휴지통 · 버전 기록 · 시설 둘러보기 사진을 DB로 (2026-10-19)

-- 1) 카드 휴지통: 지운 카드는 바로 없애지 않고 지운 시각 · 지운 사람을 적어 휴지통으로(사이트 · 관리 목록에서는 빠짐)
ALTER TABLE life_foods ADD COLUMN deleted_at TIMESTAMP;
ALTER TABLE life_foods ADD COLUMN deleted_by BIGINT;
ALTER TABLE life_spots ADD COLUMN deleted_at TIMESTAMP;
ALTER TABLE life_spots ADD COLUMN deleted_by BIGINT;

-- 2) 시설 둘러보기 사진: 공간(사이트 life/index.html 의 bx9s-층-번호)마다 사진 넘김의 사진들. 층 · 공간 이름과 안내 글은 페이지에 그대로
CREATE TABLE life_facility_photos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id    VARCHAR(20)  NOT NULL,                -- 공간(bx9s-1-0 등)
    photo_class VARCHAR(60),                          -- 사이트에 원래 있던 그림(life.css 의 im-이름)
    photo       VARCHAR(300),                         -- 올린 사진(life/ 기준 주소). photo_class 와 둘 중 하나
    zoom        VARCHAR(10),                          -- 확대(예: 230%, 비우면 꽉 차게)
    pos         VARCHAR(30),                          -- 가운데에 보일 곳(예: 70% 40%)
    caption     VARCHAR(120) NOT NULL,                -- 사진 설명(사진 아래 · 화면 낭독기)
    sort_order  INT          NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_life_facility_photos_order ON life_facility_photos (space_id, sort_order);

-- 공간마다 사진 왼쪽 위 표시: '' 표시 안 함 · ex 사진 예시 · tmp 임시 사진
CREATE TABLE life_facility_spaces (
    space_id    VARCHAR(20)  PRIMARY KEY,
    badge       VARCHAR(10)  NOT NULL DEFAULT '',
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3) 버전 기록: 목록(오늘 점심 · 바람 쐬러 가요 · 시설 사진)을 바꿀 때마다 바로 전 모습을 통째로 남긴다(되돌리기에 씀)
CREATE TABLE life_versions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section     VARCHAR(10)  NOT NULL,                -- food | fun | fac
    reason      VARCHAR(20)  NOT NULL,                -- SAVE 저장 전 · RESTORE 되돌리기 전 · TRASH_RESTORE 휴지통에서 꺼내기 전
    summary     VARCHAR(200) NOT NULL,                -- 예: 식당 13곳 · 카페 7곳
    data        TEXT         NOT NULL,                -- 그때 목록 전체(JSON)
    created_by  BIGINT,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_life_versions_section ON life_versions (section, id);
